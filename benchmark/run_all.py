"""Whole benchmark for one home, one command.

    python -m benchmark.run_all --capture-dir <cozmo_capture> --sheet <sheet.json> \
        --out benchmark/results/home

<cozmo_capture>/ is what the capture protocol produces:
    spectacular_*/            Spectacular Rec recordings (video tier, repeated walks)
    *.mov | *.mp4             stock-Camera clip (fallback video tier, pivot scans)
    photos/<NN_room>/         stills, one folder per room (photo tier)
    lidar_*/                  StrayScanner exports, if a Pro phone was available

For every capture: run the tier, map the tape sheet onto the plan
(benchmark/sheet.py), score the gates (benchmark/ground_truth.py). Across
repeated walks of the same tier: wall-length and ceiling repeatability,
keyed by the SHEET's wall letters (so the correspondence comes from the
tape labels, not from the pipeline's own wall order). Writes summary.json
and report.md; every number in report.md is regenerated by this command.
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np

from benchmark.ground_truth import score
from benchmark.sheet import to_ground_truth, _mean

VIDEO_EXT = {".mov", ".mp4", ".m4v", ".MOV", ".MP4"}
WALL_TOL = {"lidar": None, "video": 0.03, "photo": 0.08}     # brief: photo +-8 %, video +-3 % (relative)


def discover(cdir: Path) -> list[dict]:
    caps = []
    for d in sorted(cdir.iterdir()):
        if d.is_dir() and d.name.lower().startswith("spectacular"):
            caps.append({"name": d.name, "tier": "video", "kind": "posed", "path": d})
        elif d.is_dir() and d.name.lower().startswith("lidar"):
            caps.append({"name": d.name, "tier": "lidar", "kind": "lidar", "path": d})
        elif d.is_file() and d.suffix in VIDEO_EXT:
            caps.append({"name": d.stem, "tier": "video", "kind": "pivot", "path": d})
    if (cdir / "photos").is_dir():
        caps.append({"name": "photos", "tier": "photo", "kind": "photo", "path": cdir / "photos"})
    return caps


def run_capture(c: dict, out: Path) -> dict:
    from cli.run import run_lidar, run_posed_video, run_monocular
    o = out / c["name"]
    if c["kind"] == "lidar":
        return run_lidar(c["path"], o)
    if c["kind"] == "posed":
        return run_posed_video(c["path"], o)
    return run_monocular(c["path"], o, c["tier"])


def measured_room_area(plan_room: dict, gt_room: dict) -> tuple[float | None, float | None]:
    """Floor area from the TAPE lengths: walk the plan's wall directions
    with measured lengths (predicted where the tape has none). Returns
    (area_m2, closure_gap_m); a large gap means the sheet and the plan
    disagree on the room's shape and the area should not be trusted."""
    meas = {w["wall_id"]: w["measured"] for w in gt_room["walls"]}
    if not any(v is not None for v in meas.values()):
        return None, None
    pts = [np.zeros(2)]
    for w in plan_room["walls"]:
        p0, p1 = np.array(w["p0"], float), np.array(w["p1"], float)
        d = (p1 - p0) / (np.linalg.norm(p1 - p0) + 1e-12)
        L = meas.get(w["wall_id"]) or w["length_m"]["value"]
        pts.append(pts[-1] + d * L)
    gap = float(np.linalg.norm(pts[-1] - pts[0]))
    P = np.array(pts[:-1])
    area = 0.5 * abs(np.dot(P[:, 0], np.roll(P[:, 1], -1)) - np.dot(P[:, 1], np.roll(P[:, 0], -1)))
    return float(area), gap


def wall_rel_errors(gt: dict) -> list[float]:
    return [abs(w["predicted"] - w["measured"]) / w["measured"]
            for r in gt["rooms"] for w in r["walls"] if w["measured"]]


def repeatability(runs: list[dict], sheet: dict) -> dict:
    """runs: [{"name", "plan", "gt"}] of one tier. Keyed by (sheet room, letter)."""
    by_key, ceil = {}, {}
    for run in runs:
        rooms = {r["room_id"]: r for r in run["plan"]["rooms"]}
        for m in run["gt"]["matching"]["room_matches"]:
            pr = rooms[m["plan_room"]]
            walls = {w["wall_id"]: w for w in pr["walls"]}
            for letter, wid in m["walls"].items():
                by_key.setdefault((m["sheet_room"], letter), []).append(walls[wid]["length_m"]["value"])
            if pr["ceiling_observed"]:
                ceil.setdefault(m["sheet_room"], []).append(pr["ceiling_height_m"]["value"])
    n = len(runs)
    rows, n_ok, n_cmp = [], 0, 0
    for (room, letter), vals in sorted(by_key.items()):
        complete = len(vals) == n
        spread = max(vals) - min(vals) if len(vals) > 1 else None
        tol = max(0.01, 0.005 * float(np.mean(vals)))
        ok = complete and spread is not None and spread <= tol
        if complete and len(vals) > 1:
            n_cmp += 1
            n_ok += ok
        rows.append({"room": room, "wall": letter, "lengths_m": [round(v, 4) for v in vals],
                     "spread_m": None if spread is None else round(spread, 4), "tol_m": round(tol, 4),
                     "found_in_all_runs": complete, "pass": ok})
    crow = [{"room": k, "heights_m": [round(v, 4) for v in v_], "spread_m": round(max(v_) - min(v_), 4),
             "pass_1cm": (max(v_) - min(v_)) <= 0.01 and len(v_) == n} for k, v_ in ceil.items()]
    return {"runs": n, "walls": rows, "walls_pass": n_ok, "walls_compared": n_cmp,
            "wall_pass_rate": round(n_ok / n_cmp, 3) if n_cmp else None, "ceilings": crow}


def _fmt(x, nd=3, pct=False):
    if x is None:
        return "—"
    return f"{100 * x:.1f}%" if pct else f"{x:.{nd}f}"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--capture-dir", required=True)
    ap.add_argument("--sheet", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--only", nargs="*", help="capture names to (re)run; others reuse their plan.json")
    a = ap.parse_args(argv)
    cdir, out = Path(a.capture_dir), Path(a.out)
    sheet = json.loads(Path(a.sheet).read_text())
    out.mkdir(parents=True, exist_ok=True)

    results = []
    for c in discover(cdir):
        pj = out / c["name"] / "plan.json"
        t0 = time.time()
        if a.only is None or c["name"] in a.only or not pj.exists():
            try:
                plan = run_capture(c, out)
            except SystemExit as e:          # tier refused the input (e.g. no pivot found)
                results.append({**c, "error": str(e)})
                continue
            except Exception as e:  # noqa: BLE001 - one bad capture must not stop the benchmark
                results.append({**c, "error": f"{type(e).__name__}: {e}"})
                continue
        else:
            plan = json.loads(pj.read_text())
        gt, rep = to_ground_truth(plan, sheet)
        (out / c["name"] / "ground_truth.json").write_text(json.dumps(gt, indent=2))
        sc = score(plan, gt)
        rooms = {r["room_id"]: r for r in plan["rooms"]}
        areas, gaps = [], []
        for g in gt["rooms"]:
            ar, gap = measured_room_area(rooms[g["room_id"]], g)
            if ar is not None:
                areas.append((rooms[g["room_id"]]["floor_area_m2"]["value"], ar))
                gaps.append(gap)
        pred_fp = sum(p for p, _ in areas)
        meas_fp = sum(m for _, m in areas)
        rel = wall_rel_errors(gt)
        results.append({**{k: str(v) for k, v in c.items()}, "plan": plan, "gt": gt, "score": sc,
                        "wall_rel_err": rel, "footprint_pred_m2": pred_fp, "footprint_meas_m2": meas_fp,
                        "footprint_err_pct": 100 * (pred_fp - meas_fp) / meas_fp if meas_fp else None,
                        "closure_gaps_m": gaps, "runtime_s": plan.get("timing_s", {}).get("total",
                                                                                         round(time.time() - t0, 1))})

    # repeatability per tier (only tiers with >1 run)
    rep_by_tier = {}
    for tier in ("lidar", "video", "photo"):
        runs = [r for r in results if r["tier"] == tier and "gt" in r and r.get("kind") != "pivot"]
        if len(runs) > 1:
            rep_by_tier[tier] = repeatability(runs, sheet)

    summary = {"sheet": sheet.get("capture_id"), "captures": [], "repeatability": rep_by_tier}
    for r in results:
        if "error" in r:
            summary["captures"].append({"name": r["name"], "tier": r["tier"], "error": r["error"]})
            continue
        s = r["score"]
        rel = r["wall_rel_err"]
        tol = WALL_TOL.get(r["tier"])
        summary["captures"].append({
            "name": r["name"], "tier": r["tier"], "kind": r["kind"], "runtime_s": r["runtime_s"],
            "rooms_found": len(r["plan"]["rooms"]),
            "rooms_matched": [m["plan_room"] + "=" + m["sheet_room"] for m in r["gt"]["matching"]["room_matches"]],
            "walls_measured": len(rel),
            "wall_rel_err_median": float(np.median(rel)) if rel else None,
            "wall_rel_err_max": float(max(rel)) if rel else None,
            "walls_within_tier_tol": (sum(e <= tol for e in rel) / len(rel)) if (rel and tol) else None,
            "wall_abs_err_median_m": s["wall_length_abs_error_m"]["median"],
            "openings": s["gates"]["opening_widths"],
            "ceiling": s["gates"]["ceiling_height"],
            "ci95_coverage": s["calibration_95ci_coverage"],
            "footprint_pred_m2": r["footprint_pred_m2"], "footprint_meas_m2": r["footprint_meas_m2"],
            "footprint_err_pct": r["footprint_err_pct"],
            "max_closure_gap_m": max(r["closure_gaps_m"]) if r["closure_gaps_m"] else None,
            "drift_ablation": r["plan"].get("drift_ablation"), "drift_decision": r["plan"].get("drift"),
        })
    (out / "summary.json").write_text(json.dumps(summary, indent=2, default=str))
    (out / "report.md").write_text(render_report(summary))
    print((out / "report.md").read_text())


def render_report(S: dict) -> str:
    L = ["# Benchmark — measured home", "",
         "Regenerate: `python -m benchmark.run_all --capture-dir <dir> --sheet <sheet.json> --out <this dir>`", "",
         "## Per capture", "",
         "| capture | tier | rooms found | walls measured | wall err median | within tier tol | "
         "openings ≤2 cm (missed/phantom) | ceiling | footprint err | 95% CI coverage | runtime |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in S["captures"]:
        if "error" in c:
            L.append(f"| {c['name']} | {c['tier']} | failed: {c['error'][:80]} |||||||||")
            continue
        op = c["openings"]
        opstr = (f"{op['within_2cm']}/{op['scored']} ({op['missed']}/{op['phantom']})" if op["scored"] else "—")
        ce = c["ceiling"]["rooms"]
        cstr = "; ".join(f"{x['room_id']}: " + ("not seen" if not x["observed"] else f"{100 * x['error_m']:.1f} cm")
                         for x in ce) or "—"
        cov = c["ci95_coverage"]
        L.append(f"| {c['name']} | {c['tier']} | {c['rooms_found']} | {c['walls_measured']} | "
                 f"{_fmt(c['wall_rel_err_median'], pct=True)} | {_fmt(c['walls_within_tier_tol'], pct=True)} | "
                 f"{opstr} | {cstr} | {_fmt(c['footprint_err_pct'] / 100 if c['footprint_err_pct'] is not None else None, pct=True)} | "
                 f"{cov['inside']}/{cov['total']} | {c['runtime_s']} s |")
    L += ["", "Wall error is relative (|pred − tape| / tape). Tier tolerance: video 3 %, photo 8 %. "
          "Openings: a missed and a phantom opening each count as a miss. "
          "Footprint: sum of matched rooms vs the same rooms built from tape lengths.", ""]
    for tier, R in S["repeatability"].items():
        L += [f"## Repeatability — {tier} ({R['runs']} runs)", "",
              f"Walls within max(1 cm, 0.5 %) across all runs: **{R['walls_pass']}/{R['walls_compared']}**", "",
              "| room | wall | lengths (m) | spread | pass |", "|---|---|---|---|---|"]
        for w in R["walls"]:
            L.append(f"| {w['room']} | {w['wall']} | {', '.join(f'{v:.3f}' for v in w['lengths_m'])} | "
                     f"{_fmt(w['spread_m'])} | {'yes' if w['pass'] else 'no'} |")
        if R["ceilings"]:
            L += ["", "| room | ceiling heights (m) | spread | ≤1 cm |", "|---|---|---|---|"]
            for x in R["ceilings"]:
                L.append(f"| {x['room']} | {', '.join(f'{v:.3f}' for v in x['heights_m'])} | "
                         f"{x['spread_m']:.3f} | {'yes' if x['pass_1cm'] else 'no'} |")
        L.append("")
    abl = [c for c in S["captures"] if c.get("drift_ablation")]
    if abl:
        L += ["## Drift on/off (video tier)", "",
              "| capture | footprint OFF | footprint ON | tape footprint | auto chose | registration OFF→ON |",
              "|---|---|---|---|---|---|"]
        for c in abl:
            d = c["drift_ablation"]
            dec = c.get("drift_decision") or {}
            L.append(f"| {c['name']} | {d['off']['footprint_m2']:.2f} | {d['on']['footprint_m2']:.2f} | "
                     f"{_fmt(c['footprint_meas_m2'], 2)} | {'on' if dec.get('applied') else 'off'} | "
                     f"{d['off']['registration_voxels']} → {d['on']['registration_voxels']} |")
        L.append("")
    return "\n".join(L)


if __name__ == "__main__":
    main()
